from email.utils import parsedate_to_datetime
from io import BytesIO
from xml.etree.ElementTree import fromstring

import httpx
import pytest
from fastapi import FastAPI, UploadFile
from PIL import Image

from tests.data import seed_aeds


def image_file():
    content = BytesIO()
    Image.new('RGB', (4, 4), color=(37, 83, 149)).save(content, format='PNG')
    content.seek(0)
    return UploadFile(content, filename='aed.png')


@pytest.mark.asyncio
async def test_uploaded_photo_has_durable_bytes_before_report_publication(database):
    from services.photo_report_service import PhotoReportService
    from services.photo_service import PhotoService

    first = await PhotoService.upload(123, 456, image_file())
    second = await PhotoService.upload(789, 456, image_file())
    assert first.id != second.id
    assert first.file_path.read_bytes().startswith(b'RIFF')
    assert await PhotoReportService.create(first.id)
    assert await PhotoReportService.create(first.id)
    reports = await PhotoReportService.get_recent()
    assert len(reports) == 1
    assert reports[0].photo.node_id == 123
    assert reports[0].photo_id == first.id


@pytest.mark.asyncio
async def test_photo_upload_publishes_file_and_updates_remote_node_tags(database, monkeypatch):
    import openstreetmap
    from api.v1.photos import router
    from services.photo_service import PhotoService

    await seed_aeds([(1003, 4, {'emergency': 'defibrillator'}, 21.3, 51.2, [])])
    uploads = []

    def handler(request):
        if request.url.path.endswith('/user/details.json'):
            return httpx.Response(200, json={'user': {'id': 2004, 'blocks': {'received': {'active': 0}}}})
        if request.url.path.endswith('/node/1003'):
            return httpx.Response(
                200,
                text='<osm><node id="1003" version="4" lat="51.2" lon="21.3">'
                '<tag k="emergency" v="defibrillator"/></node></osm>',
            )
        if request.url.path.endswith('/create'):
            return httpx.Response(200, text='807')
        if request.url.path.endswith('/upload'):
            uploads.append(request.content)
        return httpx.Response(200)

    app = FastAPI()
    app.include_router(router, prefix='/api/v1')
    image = image_file()
    try:
        async with httpx.AsyncClient(transport=httpx.MockTransport(handler)) as upstream:
            monkeypatch.setattr(openstreetmap, 'HTTP', upstream)
            async with httpx.AsyncClient(transport=httpx.ASGITransport(app), base_url='http://test') as client:
                response = await client.post(
                    '/api/v1/photos/upload',
                    data={
                        'node_id': '1003',
                        'file_license': 'CC0',
                        'oauth2_credentials': '{"access_token":"example-token"}',
                    },
                    files={'file': ('aed.png', image.file, 'image/png')},
                )
    finally:
        await image.close()

    assert response.status_code == 200
    assert response.json() is True
    assert len(uploads) == 1
    modified = fromstring(uploads[0]).find('modify/node')  # noqa: S314 - application-generated XML
    assert modified is not None
    assert modified.attrib['changeset'] == '807'
    tags = {tag.attrib['k']: tag.attrib['v'] for tag in modified.findall('tag')}
    assert tags['emergency'] == 'defibrillator'
    assert tags['image:license'] == 'CC0'
    assert tags['image'].startswith('http://test/api/v1/photos/view/')
    photo_id = tags['image'].rsplit('/', 1)[1].removesuffix('.webp')
    photo = await PhotoService.get_by_id(photo_id)
    assert photo is not None
    assert photo.node_id == 1003
    assert photo.user_id == 2004


@pytest.mark.asyncio
async def test_photo_report_feed_preserves_ids_links_dates_and_html_content(database):
    from api.v1.photos import router
    from services.photo_report_service import PhotoReportService
    from services.photo_service import PhotoService

    photo = await PhotoService.upload(123, 456, image_file())
    await PhotoReportService.create(photo.id)
    report = (await PhotoReportService.get_recent())[0]
    app = FastAPI()
    app.include_router(router, prefix='/api/v1')
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app), base_url='http://test') as client:
        response = await client.get('/api/v1/photos/report/rss.xml')

    assert response.status_code == 200
    assert response.headers['content-type'].startswith('application/rss+xml')
    feed = fromstring(response.content)  # noqa: S314 - XML generated by our application
    assert feed.attrib['version'] == '2.0'
    channel = feed.find('channel')
    assert channel is not None
    assert channel.findtext('title') == 'AED Photo Reports'
    assert channel.findtext('link') == 'http://test/api/v1/photos/report/rss.xml'
    link = channel.find('{http://www.w3.org/2005/Atom}link')
    assert link is not None
    assert link.attrib == {'href': 'http://test/api/v1/photos/report/rss.xml', 'rel': 'self'}
    items = channel.findall('item')
    assert len(items) == 1
    item = items[0]
    assert item.findtext('guid') == report.id
    guid = item.find('guid')
    assert guid is not None
    assert guid.attrib['isPermaLink'] == 'false'
    assert item.findtext('link') == f'http://test/api/v1/photos/view/{photo.id}.webp'
    assert item.findtext('description') == (f'File name: {photo.file_path.name}<br>Node: https://osm.org/node/123')
    published = item.findtext('pubDate')
    assert published is not None
    assert parsedate_to_datetime(published) == report.created_at.replace(microsecond=0)


@pytest.mark.asyncio
async def test_range_request_cannot_poison_full_photo_response(database):
    from api.v1.photos import router
    from middlewares.cache_control_middleware import CacheControlMiddleware
    from services.photo_service import PhotoService

    photo = await PhotoService.upload(1001, 2002, image_file())
    content = photo.file_path.read_bytes()
    app = FastAPI()
    app.include_router(router, prefix='/api/v1')
    app.add_middleware(CacheControlMiddleware)
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app), base_url='http://test') as client:
        partial = await client.get(f'/api/v1/photos/view/{photo.id}.webp', headers={'Range': 'bytes=0-3'})
        full = await client.get(f'/api/v1/photos/view/{photo.id}.webp')
    assert partial.status_code == 206
    assert partial.content == content[:4]
    assert full.status_code == 200
    assert full.content == content


@pytest.mark.asyncio
async def test_local_photo_conditionals_and_ranges_preserve_file_identity(database):
    from api.v1.photos import router
    from middlewares.cache_control_middleware import CacheControlMiddleware
    from services.photo_service import PhotoService

    photo = await PhotoService.upload(1031, 2042, image_file())
    app = FastAPI()
    app.include_router(router, prefix='/api/v1')
    app.add_middleware(CacheControlMiddleware)
    path = f'/api/v1/photos/view/{photo.id}.webp'
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app), base_url='http://test') as client:
        full = await client.get(path)
        unchanged = await client.get(path, headers={'If-None-Match': f'"other", W/{full.headers["etag"]}'})
        since = await client.get(path, headers={'If-Modified-Since': full.headers['last-modified']})
        changed = await client.get(
            path,
            headers={
                'If-None-Match': '"different"',
                'If-Modified-Since': full.headers['last-modified'],
            },
        )
        partial = await client.get(path, headers={'Range': 'bytes=1-4', 'If-Range': full.headers['etag']})
        fallback = await client.get(path, headers={'Range': 'bytes=1-4', 'If-Range': 'W/' + full.headers['etag']})
    assert unchanged.status_code == since.status_code == 304
    assert unchanged.content == b''
    assert unchanged.headers['cache-control'] == full.headers['cache-control']
    assert changed.content == fallback.content == full.content
    assert partial.status_code == 206
    assert partial.content == full.content[1:5]
